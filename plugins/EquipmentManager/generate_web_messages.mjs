// Keep the browser fallback and Host localization calls aligned with one source.
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const directory = dirname(fileURLToPath(import.meta.url));
const source = JSON.parse(await readFile(join(directory, "assets/web/messages.en.json"), "utf8"));
const placeholders = Array.from({ length: 8 }, (_, index) => `{${index}}`);
const calls = Object.entries(source).map(([key, fallback]) => {
  const operation = /\{[0-7]\}/.test(fallback) ? "Format" : "Text";
  const argumentsTail = operation === "Format" ? ", placeholders" : "";
  return `        {${JSON.stringify(key)}, localizer.${operation}(${JSON.stringify(key)}, ${JSON.stringify(fallback)}${argumentsTail})}`;
});
const header = `#pragma once
// Generated by generate_web_messages.mjs from assets/web/messages.en.json.

#include <anomaly/sdk/localization.hpp>
#include <nlohmann/json.hpp>
#include <array>
#include <string_view>

namespace equipment_manager {

inline nlohmann::json BuildWebMessages(const anomaly::sdk::Localizer& localizer) {
    constexpr std::array<std::string_view, 8> placeholders{${placeholders.map((value) => JSON.stringify(value)).join(", ")}};
    return nlohmann::json{
${calls.join(",\n")}
    };
}

}  // namespace equipment_manager
`;
await writeFile(join(directory, "web_messages.hpp"), header, "utf8");
await writeFile(join(directory, "assets/web/messages.js"), `// Generated by generate_web_messages.mjs from messages.en.json.\nexport const fallbackMessages = Object.freeze(${JSON.stringify(source, null, 2)});\n`, "utf8");
