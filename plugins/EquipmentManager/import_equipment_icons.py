"""Pack the supplied equipment PNGs without resizing or changing their pixels.

The web host preloads at most 64 files. An atlas keeps the original game icons
within that limit; the manifest keys remain the actual Unreal asset paths.
Requires Pillow and the static equipment catalog. This is an asset import tool,
not part of the plugin runtime. Rarity comes from catalog metadata, not pixels.
"""
from __future__ import annotations

import argparse
from contextlib import closing
import json
import math
from pathlib import Path
import sqlite3

from PIL import Image


def icon_quality_order(catalog: Path, requested: set[str]) -> dict[str, int]:
    order = {"ORANGE": 0, "GOLD": 0, "PURPLE": 1, "BLUE": 2}
    result: dict[str, int] = {}
    with closing(sqlite3.connect(catalog.as_uri() + "?mode=ro", uri=True)) as database:
        for quality, path in database.execute(
                "SELECT quality, icon_path FROM equipment_item WHERE kind='core' AND icon_path IS NOT NULL"):
            key = path.split(".", 1)[0].lower()
            if key not in requested:
                continue
            rank = order[quality.upper()]
            if key in result and result[key] != rank:
                raise ValueError(f"The catalog assigns multiple rarities to one icon: {key}")
            result[key] = rank
    missing = requested - result.keys()
    if missing:
        raise ValueError(f"The catalog has no rarity metadata for: {', '.join(sorted(missing))}")
    return result


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--content-root", required=True, type=Path)
    parser.add_argument("--equipment-icons", required=True, type=Path)
    parser.add_argument("--equipment-catalog", required=True, type=Path,
                        help="Read-only game_static.sqlite3 catalog containing equipment_item icon paths and rarities.")
    args = parser.parse_args()
    content = args.content_root.resolve(strict=True)
    directory = args.equipment_icons.resolve(strict=True)
    directory.relative_to(content)
    sources = sorted(directory.rglob("*.png"), key=lambda path: path.as_posix().lower())
    if not sources:
        parser.error("The equipment directory contains no PNG files.")
    keys = {source: "/game/" + source.relative_to(content).with_suffix("").as_posix().lower() for source in sources}
    quality_order = icon_quality_order(args.equipment_catalog.resolve(strict=True), set(keys.values()))
    sources.sort(key=lambda source: (quality_order[keys[source]], keys[source]))

    images: list[tuple[str, Image.Image]] = []
    for source in sources:
        key = keys[source]
        with Image.open(source) as image:
            if image.format != "PNG":
                raise ValueError(f"Expected a PNG game resource: {source}")
            images.append((key, image.convert("RGBA")))
    columns = min(8, math.ceil(math.sqrt(len(images))))
    cell_width = max(image.width for _, image in images) + 2
    cell_height = max(image.height for _, image in images) + 2
    atlas = Image.new("RGBA", (columns * cell_width, math.ceil(len(images) / columns) * cell_height))
    sprites = {}
    for index, (key, image) in enumerate(images):
        x, y = (index % columns) * cell_width + 1, (index // columns) * cell_height + 1
        atlas.paste(image, (x, y))
        sprites[key] = {"atlas": "images-equipment.png", "x": x, "y": y,
                        "width": image.width, "height": image.height,
                        "atlasWidth": atlas.width, "atlasHeight": atlas.height}

    target = Path(__file__).resolve().parent / "assets" / "web"
    atlas.save(target / "images-equipment.png", optimize=True, compress_level=9)
    (target / "game_images.js").write_text(
        "// Generated by import_equipment_icons.py from the supplied game PNGs.\n"
        "// Actual UE package paths; no character card or portrait is bundled here.\n"
        "export const gameImageSprites = Object.freeze("
        + json.dumps(sprites, ensure_ascii=True, separators=(",", ":")) + ");\n", encoding="utf-8")
    files = list(target.rglob("*"))
    files = [path for path in files if path.is_file()]
    size = sum(path.stat().st_size for path in files)
    if len(files) > 64 or size > 8 * 1024 * 1024:
        raise ValueError("The web package exceeds the host's 64-file / 8-MiB asset budget.")
    print(json.dumps({"equipment_icons": len(images), "atlas_size": list(atlas.size),
                      "quality_counts": {quality: sum(rank == index for rank in quality_order.values())
                                         for index, quality in enumerate(("Gold", "Purple", "Blue"))},
                      "web_files": len(files), "web_bytes": size}))


if __name__ == "__main__":
    main()
